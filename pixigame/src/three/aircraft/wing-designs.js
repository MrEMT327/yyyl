// Independent native-space assemblies: +X starboard, -Z forward, +Y up.
// Shared by the actual 3D panels and inventory silhouettes.
const p = (name, points, y = 0, depth = .18, paint = 'paint') => ({ name, points, y, depth, paint });
function arc(name, cx, cz, rx, rz, width, start, end, y, depth, paint) {
  const points = [], steps = Math.ceil((end - start) / 8);
  for (let i = 0; i <= steps; i++) {
    const a = (start + (end - start) * i / steps) * Math.PI / 180;
    points.push([cx + rx * Math.cos(a), cz + rz * Math.sin(a)]);
  }
  for (let i = steps; i >= 0; i--) {
    const a = (start + (end - start) * i / steps) * Math.PI / 180;
    points.push([cx + (rx - width) * Math.cos(a), cz + (rz - width) * Math.sin(a)]);
  }
  return { ...p(name, points, y, depth, paint), frame: true };
}

